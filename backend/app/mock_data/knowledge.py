def search_knowledge(query: str, top_k: int = 5, domain: str = None) -> list[dict]:
    """模拟语义搜索"""
    results = []

    for item in KNOWLEDGE_BASE:
        if domain and item["domain"] != domain and domain != "通用":
            continue

        # 简单关键词匹配打分
        score = 0
        query_lower = query.lower()
        for kw in item["keywords"]:
            if kw.lower() in query_lower or query_lower in kw.lower():
                score += 0.3
        if item["domain"].lower() in query_lower:
            score += 0.2
        for word in query.split():
            if word.lower() in item["title"].lower():
                score += 0.15
            if word.lower() in item["content"].lower():
                score += 0.1

        score = min(score, 1.0) * item["relevance_score"]

        if score > 0.1:
            results.append({
                "doc_id": item["doc_id"],
                "title": item["title"],
                "domain": item["domain"],
                "type": item["type"],
                "source": item["source"],
                "content": item["content"][:200] + "..." if len(item["content"]) > 200 else item["content"],
                "full_content": item["content"],
                "relevance": round(score, 3),
            })

    results.sort(key=lambda x: x["relevance"], reverse=True)
    return results[:top_k]
